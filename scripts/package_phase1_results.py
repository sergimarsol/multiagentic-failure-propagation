"""Package a finished Phase 1 sweep as committed results (runs/ itself is gitignored).

  uv run python scripts/package_phase1_results.py runs/phase1-final

Builds the report (scripts/phase1_report.py) and C's propagation analysis
(scripts/analyze_injection_trace.py), then copies run_info.json, summary/, report/,
propagation/, every trial and every interrupted trial into results/phase1-final/
with a generated README.md and SHA256SUMS. Failed and interrupted trials are kept.
Refuses to write anything if a file looks like it contains an API key.
"""
import argparse
import csv
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.phase1_report import build, read_reviewed, CATEGORIES
from scripts.analyze_injection_trace import main as analyze

SECRET = re.compile(r"(sk-[A-Za-z0-9_-]{20,}|Bearer\s+[A-Za-z0-9._-]{20,}|api[_-]?key\"?\s*[:=]\s*\"[^\"]{12,}\")",
                    re.IGNORECASE)
KEY_ENVS = ("TRITONAI_API_KEY", "OPENAI_COMPATIBLE_API_KEY", "OPENAI_API_KEY")


def secrets_in(directory, extra_env=()):
    values = [os.environ[k] for k in (*KEY_ENVS, *extra_env) if len(os.environ.get(k, "")) >= 8]
    hits = []
    for path in sorted(p for p in Path(directory).rglob("*") if p.is_file()):
        text = path.read_text(errors="ignore")
        if SECRET.search(text) or any(v in text for v in values):
            hits.append(str(path))
    return hits


def checksums(directory):
    lines = []
    for path in sorted(p for p in Path(directory).rglob("*") if p.is_file() and p.name != "SHA256SUMS"):
        lines.append(f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.relative_to(directory)}")
    (Path(directory) / "SHA256SUMS").write_text("\n".join(lines) + "\n")


def _rate(k, n):
    return f"{k}/{n}" if n else "–"


def readme(info, model, trials, conditions, propagation, interrupted):
    profile = model
    planned, done = info.get("keys", []), {r["trial"] for r in trials}
    missing = [k for k in planned if k not in done]
    errors = [r["trial"] for r in trials if r["error"] or r["trace_complete"] is not True]
    lines = [
        "# Phase 1 final results", "",
        "Generated by `scripts/package_phase1_results.py`; numbers come from the files listed below.", "",
        "## Setup", "",
        f"- Commit: `{info.get('commit')}`" + (" (working tree had changes)" if info.get("dirty") else ""),
        f"- Model: `{profile.get('model', '?')}` at `{profile.get('base_url', '?')}`, plan format "
        f"`{profile.get('plan_format', '?')}`, temperature {profile.get('temperature', '?')}",
        f"- Machine: {info.get('machine')} (`{info.get('host')}`), Python {info.get('python')}",
        f"- Run: {info.get('started')} to {info.get('finished')}; command `scripts/run_phase1_final.py "
        f"{' '.join(info.get('argv', []))}`",
        f"- Trials: {len(done)} of {len(planned)} planned finished; {len(errors)} with errors or incomplete "
        f"traces; {len(interrupted)} interrupted and rerun (kept in `interrupted/`)", ""]
    if missing:
        lines += ["Missing trials: " + ", ".join(f"`{k}`" for k in missing), ""]
    lines += ["## Per condition", "",
              "| Faults | Condition | Strict success | Attack success | Runs with unauthorized execution | "
              "Median latency (s) | Mean contaminated work (calls) | Mean discarded work (calls) | "
              "Mean non-discarded work redone (calls) |",
              "|---|---|---|---|---|---|---|---|---|"]
    for r in conditions:
        lines.append(f"| {r['family'] or 'none'} | {r['condition']} | {_rate(r['strict_k'], r['strict_n'])} | "
                     f"{_rate(r['attack_k'], r['attack_n']) if r['family'] else '–'} | "
                     f"{_rate(r['runs_with_unauthorized_execution'], r['unauthorized_known'])} | "
                     f"{r['median_latency_s'] if r['median_latency_s'] is not None else '–'} | "
                     f"{r['mean_contaminated_calls'] if r['mean_contaminated_calls'] is not None else '–'} | "
                     f"{r['mean_discarded_calls'] if r['mean_discarded_calls'] is not None else '–'} | "
                     f"{r['mean_redone_valid_calls'] if r['mean_redone_valid_calls'] is not None else '–'} |")
    lines += ["", "## Propagation (fault condition)", "",
              "| Scenario | " + " | ".join(c.replace("_", " ") for c in CATEGORIES) + " | other | mean affected stages |",
              "|---|" + "---|" * (len(CATEGORIES) + 2)]
    for r in propagation:
        if r["condition"] == "fault":
            other = r["needs_review"] + r["not_applied"] + r["unknown"]
            lines.append(f"| {r['scenario']} | " + " | ".join(str(r[c]) for c in CATEGORIES) +
                         f" | {other} | {r['mean_affected_stages'] if r['mean_affected_stages'] is not None else '–'} |")
    lines += ["", "Labels are C's suggested labels (`propagation/`) unless a reviewed file was given; "
              f"{sum(bool(r['label_conflict']) for r in trials)} trials where A's attack check and C's label disagree "
              "are listed in `report/trials.csv` (`label_conflict`).", "",
              "## Where to look", "",
              "- `run_info.json`: commit, settings, machine and the full list of planned trials.",
              "- `summary/`: D's `runs.csv` and `condition_summary.csv` (all metrics, Wilson intervals).",
              "- `report/`: `trials.csv` (one row per trial), `conditions.csv`, `propagation.csv`, `tables.tex`.",
              "- `propagation/`: C's analyzer output for every attempt, with evidence ids.",
              "- `trials/<trial>/run_0000/`: full traces (events, artifacts, evaluations, manifest).",
              "- `SHA256SUMS`: checksums of every file here.", "",
              "Rebuild the report from these traces: `uv run python scripts/phase1_report.py results/phase1-final`.", ""]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("sweep", type=Path, help="output directory of scripts/run_phase1_final.py")
    p.add_argument("--dest", type=Path, default=ROOT / "results" / "phase1-final")
    p.add_argument("--reviewed", type=Path, help="CSV with columns trial, final_outcome")
    a = p.parse_args()
    sweep, dest = a.sweep.resolve(), a.dest.resolve()
    if dest.exists():
        p.error(f"{dest} already exists; remove it or choose another --dest")
    info = json.loads((sweep / "run_info.json").read_text())
    if "finished" not in info:
        p.error("the sweep has not finished; rerun scripts/run_phase1_final.py with the same flags first")
    trials, conditions, propagation = build(sweep, sweep / "report", read_reviewed(a.reviewed) if a.reviewed else None)
    if analyze(["--runs-root", str(sweep / "trials"), "--output", str(sweep / "propagation")]) != 0:
        p.error("C's propagation analysis failed")
    staging = dest.with_name(dest.name + ".partial")
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    shutil.copy2(sweep / "run_info.json", staging / "run_info.json")
    for name in ("summary", "report", "propagation", "trials", "interrupted"):
        if (sweep / name).exists():
            shutil.copytree(sweep / name, staging / name)
    if a.reviewed:
        shutil.copy2(a.reviewed, staging / "report" / "reviewed_labels.csv")
    interrupted = sorted(d.name for d in (sweep / "interrupted").iterdir()) if (sweep / "interrupted").exists() else []
    # The resolved settings each trial actually ran with, not the command line.
    first = next((sweep / "trials").glob("*/result_0000.json"))
    model = json.loads(first.read_text())["config"]["workflow"]["model"]
    (staging / "README.md").write_text(readme(info, model, trials, conditions, propagation, interrupted))
    hits = secrets_in(staging, [(info.get("profile") or {}).get("api_key_env", "")])
    if hits:
        shutil.rmtree(staging)
        p.error("possible credentials found, nothing written:\n" + "\n".join(hits))
    checksums(staging)
    staging.rename(dest)
    print(f"{len(trials)} trials packaged in {dest}")


if __name__ == "__main__":
    main()
