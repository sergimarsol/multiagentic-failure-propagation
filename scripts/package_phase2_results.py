"""Package a finished Phase 2 sweep as committed results (runs/ itself is gitignored).

  uv run python scripts/package_phase2_results.py runs/phase2 --judgments runs/phase2-work

Builds the report (scripts/phase2_report.py), then copies run_info.json, summary/,
report/, every trial and every interrupted trial into results/phase2/ with the report as
README.md and SHA256SUMS. --judgments also copies the offline work judgments
(scripts/judge_work.py output) into work_judgments/. Failed and interrupted trials are
kept. Refuses to write anything if a file looks like it contains an API key.
"""
import argparse
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.package_phase1_results import checksums, secrets_in
from scripts.phase2_report import build


def readme(info, model, report, rows, interrupted, judged):
    planned, done = info.get("keys", []), {r["trial"] for r in rows}
    missing = [k for k in planned if k not in done]
    lines = ["# Phase 2 results", "",
             "Generated by `scripts/package_phase2_results.py`; numbers come from the files listed below.", "",
             "## Setup", "",
             f"- Commit: `{info.get('commit')}`" + (" (working tree had changes)" if info.get("dirty") else ""),
             f"- Model: `{model.get('model', '?')}` at `{model.get('base_url', '?')}`, plan format "
             f"`{model.get('plan_format', '?')}`, temperature {model.get('temperature', '?')}",
             f"- Machine: {info.get('machine')} (`{info.get('host')}`), Python {info.get('python')}",
             f"- Run: {info.get('started')} to {info.get('finished')}; command `scripts/run_phase2_banking.py "
             f"{' '.join(info.get('argv', []))}`",
             f"- Trials: {len(done)} of {len(planned)} planned finished; {len(interrupted)} interrupted and "
             "rerun (kept in `interrupted/`)", ""]
    if missing:
        lines += ["Missing trials: " + ", ".join(f"`{k}`" for k in missing), ""]
    lines += ["## Where to look", "",
              "- `run_info.json`: commit, settings, machine and the full list of planned trials.",
              "- `summary/`: D's `runs.csv` and `condition_summary.csv` (all metrics, Wilson intervals).",
              "- `report/`: `trials.csv`, `conditions.csv`, `pairs.csv`, `REPORT.md`.",
              "- `trials/<trial>/run_0000/`: full traces (events, artifacts, evaluations, checkpoints, manifest)."]
    if judged:
        lines.append("- `work_judgments/`: offline work-validity judgments and their separate cost.")
    lines += ["- `SHA256SUMS`: checksums of every file here.", "",
              "Rebuild the report from these traces: `uv run python scripts/phase2_report.py results/phase2`"
              + (" `--judgments results/phase2/work_judgments`." if judged else "."), "",
              report.split("\n", 1)[1].replace("# Phase 2 report", "").lstrip("\n")]
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("sweep", type=Path, help="output directory of scripts/run_phase2_banking.py")
    p.add_argument("--dest", type=Path, default=ROOT / "results" / "phase2")
    p.add_argument("--judgments", type=Path, help="output directory of scripts/judge_work.py for this sweep")
    a = p.parse_args(argv)
    sweep, dest = a.sweep.resolve(), a.dest.resolve()
    if dest.exists():
        p.error(f"{dest} already exists; remove it or choose another --dest")
    info = json.loads((sweep / "run_info.json").read_text())
    if "finished" not in info:
        p.error("the sweep has not finished; rerun scripts/run_phase2_banking.py with the same flags first")
    rows = build(sweep, sweep / "report", a.judgments)[0]
    staging = dest.with_name(dest.name + ".partial")
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    shutil.copy2(sweep / "run_info.json", staging / "run_info.json")
    for name in ("summary", "report", "trials", "interrupted"):
        if (sweep / name).exists():
            shutil.copytree(sweep / name, staging / name)
    if a.judgments:
        shutil.copytree(a.judgments, staging / "work_judgments")
    interrupted = sorted(d.name for d in (sweep / "interrupted").iterdir()) if (sweep / "interrupted").exists() else []
    # The resolved settings each trial actually ran with, not the command line.
    first = next((sweep / "trials").glob("*/result_0000.json"))
    model = json.loads(first.read_text())["config"]["workflow"]["model"]
    report = (sweep / "report" / "REPORT.md").read_text()
    (staging / "README.md").write_text(readme(info, model, report, rows, interrupted, bool(a.judgments)))
    hits = secrets_in(staging, [(info.get("profile") or {}).get("api_key_env", "")])
    if hits:
        shutil.rmtree(staging)
        p.error("possible credentials found, nothing written:\n" + "\n".join(hits))
    checksums(staging)
    staging.rename(dest)
    print(f"{len(rows)} trials packaged in {dest}")


if __name__ == "__main__":
    main()
